function loadLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === 'en' || stored === 'fr' ? stored : 'fr';
  } catch {
    return 'fr';
  }
}

export const daemonI18n = $state({ lang: loadLang() });

export function setDaemonLang(lang) {
  if (lang !== 'fr' && lang !== 'en') return;
  daemonI18n.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // localStorage unavailable
  }
}

/** Reactive when called from a template or an $effect (reads daemonI18n.lang). */
export function t(key, vars) {
  let text = DICT[daemonI18n.lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  }
  return text;
}
